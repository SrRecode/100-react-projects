import { useEffect, useRef, useState } from 'react'
import './feature.css'

const STORAGE_KEY = 'day07-local-assistant:v1'
const starter = { id: 'welcome', role: 'assistant', text: 'Hi! I’m a small offline demo assistant. Ask me about planning, writing, focus, or what I can do.' }

function readMessages() {
  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY) || 'null')
    return Array.isArray(saved) && saved.length ? saved : [starter]
  } catch { return [starter] }
}

function answerFor(message) {
  const text = message.toLowerCase()
  if (/\b(hello|hi|hey)\b/.test(text)) return 'Hello! What are you working on today? I can help you break it into manageable steps.'
  if (/plan|organ|priorit|todo|task/.test(text)) return 'Try this: write down the outcome, choose the next action that takes under 20 minutes, and give it a realistic due date. What is the outcome you have in mind?'
  if (/focus|distract|procrast/.test(text)) return 'A gentle reset: close one distracting tab, set a 15-minute timer, and define one visible finish line. A short focused sprint counts.'
  if (/write|draft|email|word/.test(text)) return 'Start with the point you want the reader to remember. Add one useful detail, then a clear next step. Want to share a draft for a quick structure check?'
  if (/idea|brainstorm|creative/.test(text)) return 'Let’s make three different directions: the simplest useful version, the more playful version, and the version that saves someone time. Which direction should we explore?'
  if (/help|can you|what can/.test(text)) return 'I can help you shape a plan, unblock a writing task, suggest a focus reset, or brainstorm options. This demo responds with local prompts; it does not call an AI service.'
  return 'Here’s a useful next question: what would “done for now” look like? Naming a small outcome often makes the first step easier.'
}

export default function FeatureApp() {
  const [messages, setMessages] = useState(readMessages)
  const [draft, setDraft] = useState('')
  const [notice, setNotice] = useState('')
  const end = useRef(null)
  useEffect(() => {
    try { localStorage.setItem(STORAGE_KEY, JSON.stringify(messages)); setNotice('Conversation saved on this device.') }
    catch { setNotice('Browser storage is unavailable. This conversation will not persist after closing the tab.') }
    end.current?.scrollIntoView({ behavior: 'smooth', block: 'nearest' })
  }, [messages])

  function send(event) {
    event.preventDefault()
    const text = draft.trim()
    if (!text) return
    setMessages((current) => [...current, { id: crypto.randomUUID(), role: 'user', text }, { id: crypto.randomUUID(), role: 'assistant', text: answerFor(text) }])
    setDraft('')
  }

  return (
    <main className="shell">
      <header><a href="#chat"><b>W</b> SMALL <em>TALK STUDIO</em></a><span>DAY 07 / OFFLINE DEMO</span></header>
      <section className="hero" id="chat"><div><small>A THOUGHTFUL FIRST DRAFT</small><h1>A quieter kind of chatbot.</h1><p>A private, local conversation for planning, writing, focus, and fresh ideas. No account or API key required.</p></div><b className="number">07</b></section>
      <section aria-label="Chat with the local assistant" className="chat-panel">
        <div className="chat-heading"><div><strong>Your thinking partner</strong><small>Local prompt library · not a hosted AI model</small></div><button className="soft" onClick={() => setMessages([starter])} type="button">New conversation</button></div>
        <div aria-live="polite" className="chat-messages">{messages.map((message) => <article className={`chat-message ${message.role}`} key={message.id}><small>{message.role === 'assistant' ? 'STUDIO GUIDE' : 'YOU'}</small><p>{message.text}</p></article>)}<div ref={end} /></div>
        <form className="chat-compose" onSubmit={send}><label className="sr" htmlFor="chat-draft">Your message</label><textarea id="chat-draft" maxLength="1000" onChange={(event) => setDraft(event.target.value)} onKeyDown={(event) => { if (event.key === 'Enter' && !event.shiftKey) { event.preventDefault(); event.currentTarget.form.requestSubmit() } }} placeholder="What would you like to think through?" value={draft} /><button className="primary" type="submit">Send ↗</button></form>
        <p aria-live="polite" className="helper">{notice} Replies are rule-based examples, not generated by a language model.</p>
      </section>
    </main>
  )
}
